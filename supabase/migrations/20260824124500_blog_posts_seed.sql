Another often-overlooked element is time. A question with no time limit invites hesitation and distraction. A question with a short time limit forces a quick decision, which closely mirrors real test conditions, but with lower stakes. Light competition (a scoreboard, a live rank) adds motivation without turning the session into pressure.

